namespace Nette\Caching\Storages;

use Nette;
use Nette\Caching\Cache;
use function count, is_array, is_string, strlen;
use const LOCK_NB, LOCK_SH;


/**
 * Cache file storage.
 */
class FileStorage implements Nette\Caching\Storage
{
	/*
	 * Atomic thread safe logic:
	 *
	 * 1) reading: open(r+b), lock(SH), read
	 *     - delete?: delete*, close
	 * 2) deleting: delete*
	 * 3) writing: open(r+b || wb), lock(EX), truncate*, write data, write meta, close
	 *
	 * delete* = try unlink, if fails (on NTFS) { lock(EX), truncate, close, unlink } else close (on ext3)
	 */

	/** @internal cache file structure: meta-struct size + serialized meta-struct + data */
	private const
		MetaHeaderLen = 6,
		// meta structure: array of
		MetaTime = 'time', // timestamp
		MetaSerialized = 'serialized', // is content serialized?
		MetaExpire = 'expire', // expiration timestamp
		MetaDelta = 'delta', // relative (sliding) expiration
		MetaItems = 'di', // array of dependent items (file => timestamp)
		MetaCallbacks = 'callbacks'; // array of callbacks (function, args)

	/** additional cache structure */
	private const
		File = 'file',
		Handle = 'handle';

	/** seconds that one batch of the garbage collector may spend on files */
	private const GcBatchBudget = 0.02;

	/** Probability (0-1) that a batch of the garbage collector runs on each instantiation. */
	public static float $gcProbability = 0.01;

	/** @var array<string, resource>  key => file handle */
	private array $locks;

	/** @var array<string, string>  file => version (MetaTime) of the items this storage is generating */
	private array $versions = [];


	public function __construct(
		private readonly string $dir,
		private readonly ?Journal $journal = null,
	) {
		if (!is_dir($dir) || !Nette\Utils\FileSystem::isAbsolute($dir)) {
			throw new Nette\DirectoryNotFoundException("Directory '$dir' not found or is not absolute.");
		}

		if (mt_rand() / mt_getrandmax() < static::$gcProbability) {
			$this->collectBatch();
		}
	}


	public function read(string $key): mixed
	{
		$meta = $this->readMetaAndLock($this->getCacheFile($key), LOCK_SH);
		return $meta && $this->verify($meta)
			? $this->readData($meta) // calls fclose()
			: null;
	}


	/**
	 * Verifies dependencies.
	 * @param  array<string, mixed>  $meta
	 * @param  array<string, string>  $verifying  file => version of the items verified by the outer calls
	 */
	private function verify(array $meta, array $verifying = []): bool
	{
		$verifying[$meta[self::File]] = $meta[self::MetaTime];
		do {
			if (!empty($meta[self::MetaDelta])) {
				// meta[file] was added by readMetaAndLock()
				if (filemtime($meta[self::File]) + $meta[self::MetaDelta] < time()) {
					break;
				}

				touch($meta[self::File]);

			} elseif (!empty($meta[self::MetaExpire]) && $meta[self::MetaExpire] < time()) {
				break;
			}

			if (!empty($meta[self::MetaCallbacks]) && !Cache::checkCallbacks($meta[self::MetaCallbacks])) {
				break;
			}

			if (!empty($meta[self::MetaItems])) {
				foreach ($meta[self::MetaItems] as $depFile => $time) {
					// version of an item being generated by this storage or verified by an outer call
					$known = $this->versions[$depFile] ?? $verifying[$depFile] ?? null;
					if ($known !== null) {
						if ($known !== $time) {
							break 2;
						}
						continue;
					}

					$m = $this->readMetaAndLock($depFile, LOCK_SH);
					if (($m[self::MetaTime] ?? null) !== $time || ($m && !$this->verify($m, $verifying))) {
						break 2;
					}
				}
			}

			return true;
		} while (false);

		$this->delete($meta[self::File], $meta[self::Handle]); // meta[handle] & meta[file] was added by readMetaAndLock()
		return false;
	}


	public function lock(string $key): void
	{
		$cacheFile = $this->getCacheFile($key);
		if (!is_dir($dir = dirname($cacheFile))) {
			@mkdir($dir); // @ - directory may already exist
		}

		$handle = fopen($cacheFile, 'c+b');
		if (!$handle) {
			return;
		}

		$this->locks[$key] = $handle;
		flock($handle, LOCK_EX);
		$this->versions[$cacheFile] = microtime();
	}


	/** @param  array<string, mixed>  $dependencies */
	public function write(string $key, mixed $data, array $dependencies): void
	{
		$meta = [];
		if (isset($dependencies[Cache::Expire])) {
			if (empty($dependencies[Cache::Sliding])) {
				$meta[self::MetaExpire] = $dependencies[Cache::Expire] + time(); // absolute time
			} else {
				$meta[self::MetaDelta] = (int) $dependencies[Cache::Expire]; // sliding time
			}
		}

		if (isset($dependencies[Cache::Items])) {
			foreach ($dependencies[Cache::Items] as $item) {
				$depFile = $this->getCacheFile($item);
				if (isset($this->versions[$depFile])) { // being generated by this storage
					$meta[self::MetaItems][$depFile] = $this->versions[$depFile];
					continue;
				}

				$m = $this->readMetaAndLock($depFile, LOCK_SH);
				$meta[self::MetaItems][$depFile] = $m[self::MetaTime] ?? null;
				unset($m);
			}
		}

		if (isset($dependencies[Cache::Callbacks])) {
			$meta[self::MetaCallbacks] = $dependencies[Cache::Callbacks];
		}

		if (!isset($this->locks[$key])) {
			$this->lock($key);
			if (!isset($this->locks[$key])) {
				return;
			}
		}

		$handle = $this->locks[$key];
		unset($this->locks[$key]);

		$cacheFile = $this->getCacheFile($key);
		$meta[self::MetaTime] = $this->versions[$cacheFile];
		unset($this->versions[$cacheFile]);

		if (isset($dependencies[Cache::Tags]) || isset($dependencies[Cache::Priority])) {
			if (!$this->journal) {
				throw new Nette\InvalidStateException('CacheJournal has not been provided.');
			}

			$this->journal->write($cacheFile, $dependencies);
		}

		ftruncate($handle, 0);

		if (!is_string($data)) {
			$data = $this->serializeData($data);
			$meta[self::MetaSerialized] = true;
		}

		$head = serialize($meta);
		$head = str_pad((string) strlen($head), 6, '0', STR_PAD_LEFT) . $head;
		$headLen = strlen($head);

		do {
			if (fwrite($handle, str_repeat("\x00", $headLen)) !== $headLen) {
				break;
			}

			if (fwrite($handle, $data) !== strlen($data)) {
				break;
			}

			fseek($handle, 0);
			if (fwrite($handle, $head) !== $headLen) {
				break;
			}

			flock($handle, LOCK_UN);
			fclose($handle);
			return;
		} while (false);

		$this->delete($cacheFile, $handle);
	}


	public function remove(string $key): void
	{
		$cacheFile = $this->getCacheFile($key);
		unset($this->locks[$key], $this->versions[$cacheFile]);
		$this->delete($cacheFile);
	}


	/** @param  array<string, mixed>  $conditions */
	public function clean(array $conditions): void
	{
		$all = !empty($conditions[Cache::All]);
		$collector = empty($conditions);
		$namespaces = $conditions[Cache::Namespaces] ?? null;

		// cleaning using file iterator
		if ($all || $collector) {
			$now = time();
			$finder = Nette\Utils\Finder::find('_*')
				->from($this->dir)
				->descentFilter(fn($dir) => str_starts_with($dir->getFilename(), '_')) // other directories belong to other tools, such as Latte
				->childFirst();
			foreach ($finder as $entry) {
				$path = (string) $entry;
				if ($entry->isDir()) { // collector: remove empty dirs
					@rmdir($path); // @ - removing dirs is not necessary
					continue;
				}

				if ($all) {
					$this->delete($path);

				} else { // collector
					$this->collectFile($path, LOCK_SH, $now);
				}
			}

			$this->journal?->clean($conditions);

			return;

		} elseif ($namespaces) {
			foreach ($namespaces as $namespace) {
				$dir = $this->dir . '/_' . urlencode($namespace);
				if (!is_dir($dir)) {
					continue;
				}

				foreach (Nette\Utils\Finder::findFiles('_*')->in($dir) as $entry) {
					$this->delete((string) $entry);
				}

				@rmdir($dir); // @ directory may already contain new files
			}
		}

		// cleaning using journal
		if ($this->journal) {
			foreach ($this->journal->clean($conditions) ?? [] as $file) {
				$this->delete($file);
			}
		}
	}


	/**
	 * Collects garbage in one randomly chosen directory, from a random file, until the time budget runs out,
	 * so that no request pays for walking the whole cache. Files held by another process are skipped.
	 */
	private function collectBatch(): void
	{
		$files = $dirs = [];
		foreach (scandir($this->dir) ?: [] as $name) {
			if ($name[0] !== '_') {
				continue;
			} elseif (!str_starts_with($name, '_%00') && is_dir($this->dir . '/' . $name)) { // items without namespace start with %00
				$dirs[] = $name;
			} else {
				$files[] = $name;
			}
		}

		$pick = random_int(0, count($dirs));
		if ($pick < count($dirs)) {
			$dir = $this->dir . '/' . $dirs[$pick];
			$files = array_values(array_filter(scandir($dir) ?: [], fn($name) => $name[0] === '_'));
		} else {
			$dir = $this->dir;
		}

		$count = count($files);
		$start = $count ? random_int(0, $count - 1) : 0;
		$now = time();
		$deadline = microtime(true) + self::GcBatchBudget;
		for ($i = 0; $i < $count && microtime(true) < $deadline; $i++) {
			$this->collectFile($dir . '/' . $files[($start + $i) % $count], LOCK_SH | LOCK_NB, $now);
		}

		if ($i === $count && $dir !== $this->dir) {
			@rmdir($dir); // @ - directory may already contain new files
		}
	}


	/**
	 * Deletes the file if its item has expired.
	 * @param  int<0, 7>  $lock
	 */
	private function collectFile(string $file, int $lock, int $now): void
	{
		$meta = $this->readMetaAndLock($file, $lock);
		if (!$meta) {
			return;

		} elseif ((!empty($meta[self::MetaDelta]) && filemtime($meta[self::File]) + $meta[self::MetaDelta] < $now)
			|| (!empty($meta[self::MetaExpire]) && $meta[self::MetaExpire] < $now)
		) {
			$this->delete($file, $meta[self::Handle]);
			return;
		}

		flock($meta[self::Handle], LOCK_UN);
		fclose($meta[self::Handle]);
	}


	/**
	 * Opens and locks a cache file and reads its metadata.
	 * @param  int<0, 7>  $lock
	 * @return ?array<string, mixed>  meta data with 'file' and 'handle' keys added, or null if not found
	 */
	protected function readMetaAndLock(string $file, int $lock): ?array
	{
		$handle = @fopen($file, 'r+b'); // @ - file may not exist
		if (!$handle) {
			return null;

		} elseif (!flock($handle, $lock)) { // with LOCK_NB, the file is locked by another process
			fclose($handle);
			return null;
		}

		$header = (string) stream_get_contents($handle, self::MetaHeaderLen);
		$size = strspn($header, '0123456789') === self::MetaHeaderLen ? (int) $header : 0; // (int) '0942e7' would be 9420000000
		if ($size) {
			$raw = stream_get_contents($handle, $size, self::MetaHeaderLen);
			if ($raw !== false) {
				$meta = @unserialize($raw); // @ - file may not be a valid cache file
				if (is_array($meta)) {
					$meta[self::File] = $file;
					$meta[self::Handle] = $handle;
					return $meta;
				}
			}
		}

		flock($handle, LOCK_UN);
		fclose($handle);
		return null;
	}


	/**
	 * Reads cache data from disk and closes cache file handle.
	 * @param  array<string, mixed>  $meta
	 */
	protected function readData(array $meta): mixed
	{
		$data = stream_get_contents($meta[self::Handle]);
		flock($meta[self::Handle], LOCK_UN);
		fclose($meta[self::Handle]);
		return match (true) {
			$data === false => null,
			empty($meta[self::MetaSerialized]) => $data,
			default => $this->unserializeData($data),
		};
	}


	/**
	 * Converts non-string data to the string stored in the cache file. Override it together with unserializeData()
	 * to use another format, such as igbinary; the files written in the previous format must then be cleaned.
	 */
	protected function serializeData(mixed $data): string
	{
		return serialize($data);
	}


	protected function unserializeData(string $data): mixed
	{
		return unserialize($data);
	}


	/**
	 * Returns the file path for a given cache key.
	 */
	protected function getCacheFile(string $key): string
	{
		$file = urlencode($key);
		if ($a = strrpos($file, '%00')) { // %00 = urlencode(Nette\Caching\Cache::NamespaceSeparator)
			$file = substr_replace($file, '/_', $a, 3);
		}

		return $this->dir . '/_' . $file;
	}


	/**
	 * Deletes and closes file.
	 * @param  resource  $handle
	 */
	private static function delete(string $file, $handle = null): void
	{
		if (@unlink($file)) { // @ - file may not already exist
			if ($handle) {
				flock($handle, LOCK_UN);
				fclose($handle);
			}

			return;
		}

		if (!$handle) {
			$handle = @fopen($file, 'r+'); // @ - file may not exist
		}

		if (!$handle) {
			return;
		}

		flock($handle, LOCK_EX);
		ftruncate($handle, 0);
		flock($handle, LOCK_UN);
		fclose($handle);
		@unlink($file); // @ - file may not already exist
	}
}
